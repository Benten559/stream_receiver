// Test camera publisher - simulates a camera publishing frames to Redis
// Usage: npx ts-node test_camera_publisher.ts

import { createClient } from 'redis';

const CAMERA_ID = 'test_cam1';
const CHANNEL = `camera_stream:${CAMERA_ID}`;
const FRAME_RATE = 10; // frames per second

async function main(): Promise<void> {
  // Create Redis publisher
  const publisher = createClient({
    socket: {
      host: process.env.REDIS_HOST || '192.168.8.100',
      port: parseInt(process.env.REDIS_PORT || '6379')
    }
  });

  publisher.on('error', (err) => console.error('Redis error:', err));

  await publisher.connect();
  console.log(`Connected to Redis. Publishing to channel: ${CHANNEL}`);

  // Create a simple test JPEG (1x1 red pixel)
  // This is a minimal valid JPEG file
  const testJpeg = Buffer.from([
    0xFF, 0xD8, 0xFF, 0xE0, 0x00, 0x10, 0x4A, 0x46, 0x49, 0x46, 0x00, 0x01,
    0x01, 0x00, 0x00, 0x01, 0x00, 0x01, 0x00, 0x00, 0xFF, 0xDB, 0x00, 0x43,
    0x00, 0x08, 0x06, 0x06, 0x07, 0x06, 0x05, 0x08, 0x07, 0x07, 0x07, 0x09,
    0x09, 0x08, 0x0A, 0x0C, 0x14, 0x0D, 0x0C, 0x0B, 0x0B, 0x0C, 0x19, 0x12,
    0x13, 0x0F, 0x14, 0x1D, 0x1A, 0x1F, 0x1E, 0x1D, 0x1A, 0x1C, 0x1C, 0x20,
    0x24, 0x2E, 0x27, 0x20, 0x22, 0x2C, 0x23, 0x1C, 0x1C, 0x28, 0x37, 0x29,
    0x2C, 0x30, 0x31, 0x34, 0x34, 0x34, 0x1F, 0x27, 0x39, 0x3D, 0x38, 0x32,
    0x3C, 0x2E, 0x33, 0x34, 0x32, 0xFF, 0xC0, 0x00, 0x0B, 0x08, 0x00, 0x01,
    0x00, 0x01, 0x01, 0x01, 0x11, 0x00, 0xFF, 0xC4, 0x00, 0x14, 0x00, 0x01,
    0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    0x00, 0x00, 0x00, 0x03, 0xFF, 0xC4, 0x00, 0x14, 0x10, 0x01, 0x00, 0x00,
    0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    0x00, 0x00, 0xFF, 0xDA, 0x00, 0x08, 0x01, 0x01, 0x00, 0x00, 0x3F, 0x00,
    0x7F, 0x00, 0xFF, 0xD9
  ]);

  let frameCount = 0;

  // Publish frames at specified rate
  const interval = setInterval(async () => {
    try {
      await publisher.publish(CHANNEL, testJpeg);
      frameCount++;

      if (frameCount % (FRAME_RATE * 5) === 0) {
        console.log(`Published ${frameCount} frames...`);
      }
    } catch (err) {
      console.error('Error publishing frame:', err);
    }
  }, 1000 / FRAME_RATE);

  // Handle shutdown
  process.on('SIGINT', async () => {
    console.log(`\nShutting down. Published ${frameCount} total frames.`);
    clearInterval(interval);
    await publisher.quit();
    process.exit(0);
  });

  console.log(`Publishing ${FRAME_RATE} frames per second. Press Ctrl+C to stop.`);
}

main().catch(console.error);
